create or replace function public.big2_bootstrap(p_slug text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_group_id uuid;
begin
  v_group_id := public.big2_public_group_id(p_slug);
  return public.big2_state(v_group_id);
end;
$$;

create or replace function public.big2_log_access(
  p_slug text, p_actor_id uuid, p_actor_name text
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_group_id uuid;
begin
  v_group_id := public.big2_public_group_id(p_slug);

  -- Hoogstens één bezoekregel per gebruiker per tien minuten. Deze functie is openbaar,
  -- dus zonder deze controle kan het logboek onbeperkt worden volgeschreven.
  if not exists (
    select 1 from public.big2_audit_logs
    where group_id = v_group_id
      and action = 'site_access'
      and actor_player_id is not distinct from p_actor_id
      and created_at > now() - interval '10 minutes'
  ) then
    perform public.big2_write_log(v_group_id, p_actor_id, p_actor_name, 'site_access', 'site', null, '{}'::jsonb);
  end if;

  return public.big2_state(v_group_id);
end;
$$;

create or replace function public.big2_add_game(
  p_slug text, p_actor_id uuid, p_actor_name text,
  p_entered_by uuid, p_winner uuid, p_entries jsonb, p_note text default null
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_group_id uuid;
  v_normalized jsonb;
  v_game public.big2_games%rowtype;
begin
  v_group_id := public.big2_public_group_id(p_slug);

  -- Iedereen met de link mag potjes toevoegen, dus staat hier een eenvoudige rem tegen
  -- geautomatiseerd volschrijven van de database. Normaal gebruik haalt deze grens nooit.
  if (
    select count(*) from public.big2_games
    where group_id = v_group_id and created_at > now() - interval '1 minute'
  ) >= 20 then
    raise exception 'Er zijn zojuist veel potjes achter elkaar ingevoerd. Probeer het over een minuut opnieuw.';
  end if;

  v_normalized := public.big2_normalize_entries(v_group_id, p_winner, p_entries, true);

  if not exists (
    select 1 from public.big2_players where id = p_entered_by and group_id = v_group_id and active
  ) then raise exception 'Ongeldige invoerder'; end if;

  insert into public.big2_games(group_id, entered_by, winner, entries, note)
  values (v_group_id, p_entered_by, p_winner, v_normalized, nullif(trim(p_note), ''))
  returning * into v_game;

  perform public.big2_write_log(
    v_group_id, p_actor_id, p_actor_name, 'game_added', 'game', v_game.id,
    jsonb_build_object('game', to_jsonb(v_game) - 'group_id' - 'deleted_at')
  );
  return public.big2_state(v_group_id);
end;
$$;

create or replace function public.big2_admin_update_game(
  p_slug text, p_admin_pin text, p_actor_id uuid, p_actor_name text,
  p_game_id uuid, p_winner uuid, p_entries jsonb, p_note text default null
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_group_id uuid;
  v_normalized jsonb;
  v_before public.big2_games%rowtype;
  v_after public.big2_games%rowtype;
begin
  v_group_id := public.big2_admin_group_id(p_slug, p_admin_pin);
  select * into v_before from public.big2_games
  where id = p_game_id and group_id = v_group_id and deleted_at is null;
  if not found then raise exception 'Potje niet gevonden'; end if;

  v_normalized := public.big2_normalize_entries(v_group_id, p_winner, p_entries, false);

  -- Een correctie wijzigt alleen winnaar, kaarten en opmerking. De website biedt geen knop
  -- om deelnemers te wisselen, dus dat wordt hier ook op de server geweigerd.
  if exists (
    select (v->>'player_id')::uuid from jsonb_array_elements(v_normalized) v
    except
    select (v->>'player_id')::uuid from jsonb_array_elements(v_before.entries) v
  ) or exists (
    select (v->>'player_id')::uuid from jsonb_array_elements(v_before.entries) v
    except
    select (v->>'player_id')::uuid from jsonb_array_elements(v_normalized) v
  ) then
    raise exception 'De deelnemers van een potje kunnen niet worden gewijzigd. Verwijder het potje en voer het opnieuw in.';
  end if;

  update public.big2_games
  set winner = p_winner, entries = v_normalized, note = nullif(trim(p_note), ''), updated_at = now()
  where id = p_game_id
  returning * into v_after;

  perform public.big2_write_log(
    v_group_id, p_actor_id, p_actor_name, 'game_updated', 'game', p_game_id,
    jsonb_build_object(
      'before', to_jsonb(v_before) - 'group_id' - 'deleted_at',
      'after', to_jsonb(v_after) - 'group_id' - 'deleted_at'
    )
  );
  return public.big2_state(v_group_id);
end;
$$;

create or replace function public.big2_admin_add_players(
  p_slug text, p_admin_pin text, p_actor_id uuid, p_actor_name text, p_names jsonb
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_group_id uuid;
  v_name text;
  v_player public.big2_players%rowtype;
  v_count integer;
begin
  v_group_id := public.big2_admin_group_id(p_slug, p_admin_pin);
  if jsonb_typeof(p_names) <> 'array' then raise exception 'Ongeldige namenlijst'; end if;

  select count(*) into v_count
  from (
    select distinct trim(value) as name
    from jsonb_array_elements_text(p_names)
    where char_length(trim(value)) between 2 and 40
  ) names;

  if v_count < 1 or v_count > 30 then raise exception 'Voer 1 tot 30 geldige namen in'; end if;

  for v_name in
    select distinct trim(value)
    from jsonb_array_elements_text(p_names)
    where char_length(trim(value)) between 2 and 40
    order by 1
  loop
    insert into public.big2_players(group_id, name)
    values (v_group_id, v_name)
    returning * into v_player;

    perform public.big2_write_log(
      v_group_id, p_actor_id, p_actor_name, 'player_added', 'player', v_player.id,
      jsonb_build_object('name', v_player.name)
    );
  end loop;

  return public.big2_state(v_group_id);
exception when unique_violation then raise exception 'Minstens één speler bestaat al';
end;
$$;

create or replace function public.big2_admin_set_player_active(
  p_slug text, p_admin_pin text, p_actor_id uuid, p_actor_name text,
  p_player_id uuid, p_active boolean
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_group_id uuid;
  v_player public.big2_players%rowtype;
  v_previous_active boolean;
begin
  v_group_id := public.big2_admin_group_id(p_slug, p_admin_pin);
  select * into v_player from public.big2_players where id = p_player_id and group_id = v_group_id;
  if not found then raise exception 'Speler niet gevonden'; end if;
  v_previous_active := v_player.active;
  update public.big2_players set active = p_active where id = p_player_id;
  perform public.big2_write_log(
    v_group_id, p_actor_id, p_actor_name, 'player_status_changed', 'player', p_player_id,
    jsonb_build_object('name', v_player.name, 'previous_active', v_previous_active, 'active', p_active)
  );
  return public.big2_state(v_group_id);
end;
$$;

create or replace function public.big2_admin_delete_game(
  p_slug text, p_admin_pin text, p_actor_id uuid, p_actor_name text, p_game_id uuid
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_group_id uuid;
  v_game public.big2_games%rowtype;
begin
  v_group_id := public.big2_admin_group_id(p_slug, p_admin_pin);
  select * into v_game from public.big2_games
  where id = p_game_id and group_id = v_group_id and deleted_at is null;
  if not found then raise exception 'Potje niet gevonden'; end if;

  update public.big2_games set deleted_at = now() where id = p_game_id;
  perform public.big2_write_log(
    v_group_id, p_actor_id, p_actor_name, 'game_deleted', 'game', p_game_id,
    jsonb_build_object('game', to_jsonb(v_game) - 'group_id' - 'deleted_at')
  );
  return public.big2_state(v_group_id);
end;
$$;

